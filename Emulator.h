#ifndef EMULATOR_H
#define EMULATOR_H
#include <string>
#include <SDL2/SDL.h>

constexpr int fontSize = 80;

class Emulator {
public:
    std::uint8_t memory[4096] = {0}; // 4096 bytes of memory
    std::uint8_t variableRegisters[16]{};
    bool display[64][32]{}; // 64x32 display
    std::uint16_t programCounter; // Program counter
    std::uint16_t indexRegister;
    std::uint16_t stack[16]{}; // Stack
    std::uint8_t delayTimer;
    std::uint8_t soundTimer;
    std::uint16_t instruction{};


    Emulator(std::string filename);

    void run();

private:
    SDL_Window* window;
    SDL_Renderer* renderer;
    std::uint8_t font[fontSize] = {
        0xF0, 0x90, 0x90, 0x90, 0xF0, // 0
        0x20, 0x60, 0x20, 0x20, 0x70, // 1
        0xF0, 0x10, 0xF0, 0x80, 0xF0, // 2
        0xF0, 0x10, 0xF0, 0x10, 0xF0, // 3
        0x90, 0x90, 0xF0, 0x10, 0x10, // 4
        0xF0, 0x80, 0xF0, 0x10, 0xF0, // 5
        0xF0, 0x80, 0xF0, 0x90, 0xF0, // 6
        0xF0, 0x10, 0x20, 0x40, 0x40, // 7
        0xF0, 0x90, 0xF0, 0x90, 0xF0, // 8
        0xF0, 0x90, 0xF0, 0x10, 0xF0, // 9
        0xF0, 0x90, 0xF0, 0x90, 0x90, // A
        0xE0, 0x90, 0xE0, 0x90, 0xE0, // B
        0xF0, 0x80, 0x80, 0x80, 0xF0, // C
        0xE0, 0x90, 0x90, 0x90, 0xE0, // D
        0xF0, 0x80, 0xF0, 0x80, 0xF0, // E
        0xF0, 0x80, 0xF0, 0x80, 0x80 // F
    };

    void fetch();

    void decode();

    void loadFont();

    void draw() const;
};


#endif //EMULATOR_H
